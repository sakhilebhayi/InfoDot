{ printf '%s="%s"\n' "$KAPP" "base64:FAKEKEY-PRESS="; echo 'DB_CONNECTION="sqlite"'; echo 'DB_DATABASE="database/database.sqlite"   # relative to the app'; } > "$P/.env"
# docs: host label doc -> key docs; .env only, no database at all
DC="$H/doc.$D/docs"; mkapp "$DC"; ev "$KAPP" "base64:FAKEKEY-DOCS=" > "$DC/.env"
