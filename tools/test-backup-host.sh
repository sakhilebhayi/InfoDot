runout bk inventory
check "inventory finds the 8 apps by host label (pres->press, sheets->sheet, doc->docs, dotfiles under files)" "[ $RC = 0 ] && echo \"\$OUT\" | grep -q '8 app(s) found, 8 without any backup' && for k in $KEYS; do echo \"\$OUT\" | grep -q \"^\$k \" || exit 1; done"
check "inventory flags NO-BACKUP, NO-DB (docs) and shows drivers" "echo \"\$OUT\" | grep '^docs ' | grep -q 'NO-DB' && echo \"\$OUT\" | grep '^mines ' | grep -q 'mysql' && echo \"\$OUT\" | grep '^projects ' | grep -q pgsql && echo \"\$OUT\" | grep '^tasks ' | grep -q NO-BACKUP"
check "inventory is read-only (no backup directory content created)" "[ -z \"\$(ls -A '$BKR' | grep -v '^\\.')\" ]"
runout bk inventory --strict; check "inventory --strict exits non-zero while apps are flagged" "[ $RC -ne 0 ]"

# ---- 4. the first run, with a live writer on press' WAL database ------------------------------------------------
