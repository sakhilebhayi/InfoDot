{ ev "$KAPP" "base64:FAKEKEY-FILES="; echo 'DB_CONNECTION=sqlite'; } > "$F/.env"
S="$H/sheets.$D/sheet"; mkapp "$S"; mk_sqlite "$S/database/database.sqlite" 4
{ ev "$KAPP" "base64:FAKEKEY-SHEET="; echo 'DB_CONNECTION=sqlite'; } > "$S/.env"
# mines: MySQL, password with quote, colon, backslash and hash
M="$H/mines.$D/mines"; mkapp "$M"
{ ev "$KAPP" "base64:FAKEKEY-MINES="; printf '%s\n' DB_CONNECTION=mysql DB_HOST=127.0.0.1 DB_PORT=3306 DB_DATABASE=mines_db DB_USERNAME=mines_user
  printf '%s="%s"\n' "$KPW" 'Pa\"ss:FAKEDBPW\\wd#1'; } > "$M/.env"
export STUB_PW='Pa"ss:FAKEDBPW\wd#1'
# projects: PostgreSQL
PJ="$H/projects.$D/projects"; mkapp "$PJ"
{ ev "$KAPP" "base64:FAKEKEY-PROJECTS="; printf '%s\n' DB_CONNECTION=pgsql DB_HOST=127.0.0.1 DB_PORT=5432 DB_DATABASE=projects_db DB_USERNAME=pg_user
  ev "$KPW" 'pg:FAKEPGPW\x'; } > "$PJ/.env"
TASKS_DB_SUM_BEFORE="$(cksum < "$T/database/database.sqlite")"
ENV_SUM_BEFORE="$(cksum < "$T/.env")"
KEYS="docs dopemine files mines press projects sheet tasks"

# ---- 0. help, refusals before init -----------------------------------------------------------------------------
runout bk --help; check "--help exits 0 and lists the commands" "[ $RC = 0 ] && echo \"\$OUT\" | grep -q 'dot-backup run'"
runout bk run; check "run refuses while the passphrase file is missing" "[ $RC -ne 0 ] && echo \"\$OUT\" | grep -q 'refusing' && [ ! -d '$BKR/tasks' ]"
runout bk verify; check "verify refuses while the passphrase file is missing" "[ $RC -ne 0 ] && echo \"\$OUT\" | grep -q refusing"

# ---- 1. init ---------------------------------------------------------------------------------------------------
runout bk init; check "init succeeds" "[ $RC = 0 ]"
PF="$H/.dot-backup/passphrase"
check "init created the passphrase file with mode 600" "[ \"\$(ls -ld '$PF' | cut -c1-10)\" = '-rw-------' ] && [ -s '$PF' ]"
check "init created ~/dot-backups and ~/.dot-backup with mode 700" "[ \"\$(ls -ld '$BKR' | cut -c1-10)\" = 'drwx------' ] && [ \"\$(ls -ld '$H/.dot-backup' | cut -c1-10)\" = 'drwx------' ]"
check "init never printed the passphrase" "! echo \"\$OUT\" | grep -qF \"\$(cat '$PF')\""
SUM1="$(cksum < "$PF")"; runout bk init
check "a second init leaves the passphrase unchanged" "[ \"\$(cksum < '$PF')\" = '$SUM1' ] && echo \"\$OUT\" | grep -q 'left unchanged'"

# ---- 2. wrong passphrase mode refuses --------------------------------------------------------------------------
