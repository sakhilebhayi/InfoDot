# ---- 13. retention -----------------------------------------------------------------------------------------------
RD="$BKR/ret"; mkdir -p "$RD"; chmod 700 "$RD"
for s in 20260601-020000 20260801-020000 20260815-020000 20260901-020000 20260920-020000 20261001-020000 20261005-020000 20261010-020000 20261015-020000 20261020-020000; do
