runout bk restore projects "$(newest projects)" "$R/projects"
check "PostgreSQL dump restores with its footer" "[ $RC = 0 ] && grep -q 'PostgreSQL database dump complete' '$R/projects/database.sql'"
runout bk restore press "$(newest press)" "$R/press"
