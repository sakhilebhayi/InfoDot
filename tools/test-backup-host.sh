( while [ ! -f "$W/stop" ]; do sql "$P/database/database.sqlite" "INSERT INTO items(v) VALUES ('live');" >/dev/null 2>&1; done ) &
BGPIDS="$BGPIDS $!"
sleep 0.5
runout bk run
touch "$W/stop"; sleep 0.3
check "run exits 0 and reports 8 ok" "[ $RC = 0 ] && echo \"\$OUT\" | grep -q '8 ok, 0 failed, 0 skipped'"
check "docs (.env only) is backed up with a no_database warning" "echo \"\$OUT\" | grep '^docs: ok' | grep -q no_database"
for k in $KEYS; do
  a="$(ls "$BKR/$k"/$k-*.tar.gz.enc 2>/dev/null | tail -n 1)"
  check "$k: one encrypted archive plus its .sha256, both mode 600" "[ -f '$a' ] && [ -f '$a.sha256' ] && [ \"\$(ls -ld '$a' | cut -c1-10)\" = '-rw-------' ] && [ \"\$(ls -ld '$a.sha256' | cut -c1-10)\" = '-rw-------' ]"
  check "$k: the .sha256 matches the ciphertext" "[ \"\$(cut -d' ' -f1 '$a.sha256')\" = \"\$(sha '$a')\" ]"
  check "$k: the archive is ciphertext (no SQLite header, no APP_KEY, no gzip magic)" "! grep -aq 'SQLite format 3' '$a' && ! grep -aq 'APP_KEY' '$a' && ! grep -aq 'FAKEKEY' '$a' && [ \"\$(head -c 2 '$a' | od -An -tx1 | tr -d ' ')\" != '1f8b' ] && [ \"\$(head -c 8 '$a')\" = 'Salted__' ]"
done
check "backup dirs are mode 700" "[ \"\$(ls -ld '$BKR/tasks' | cut -c1-10)\" = 'drwx------' ]"
check "manifest.log has one ok line per app with counts and no content" "[ \$(grep -c 'status=ok' '$BKR/manifest.log') = 8 ] && grep 'key=tasks ' '$BKR/manifest.log' | grep -q 'driver=sqlite db_bytes=[0-9]* archive_bytes=[0-9]* seconds=[0-9]*'"
check "staging area is empty after the run" "[ -z \"\$(ls -A '$BKR/.stage')\" ]"
check "no temporary credential file is left anywhere (my.cnf, pgpass)" "[ -z \"\$(find '$H' -name my.cnf -o -name pgpass 2>/dev/null)\" ] && ! [ -e \"\$(head -n1 '$STUB_LOG/cnf.paths')\" ] && ! [ -e \"\$(head -n1 '$STUB_LOG/pgpass.paths')\" ]"
check "mysqldump got --single-transaction --quick and the password is not on its command line" "grep -q -- '--single-transaction' '$STUB_LOG/mysqldump.args' && grep -q -- '--quick' '$STUB_LOG/mysqldump.args' && ! grep -q 'FAKEDBPW' '$STUB_LOG/mysqldump.args' && ! grep -q 'FAKEDBPW' '$STUB_LOG/pg_dump.args'"
printf '%s\n' 'password="Pa\"ss:FAKEDBPW\\wd#1"' > "$W/expect.cnf"
check "the defaults file held the correctly escaped password (quote, backslash, hash)" "grep -qxF -f '$W/expect.cnf' '$STUB_LOG/cnf.copy'"
printf '%s\n' '127.0.0.1:5432:projects_db:pg_user:pg\:FAKEPGPW\\x' > "$W/expect.pgpass"
check "the pgpass line is escaped (colon, backslash)" "grep -qxF -f '$W/expect.pgpass' '$STUB_LOG/pgpass.copy'"
check "pg_dump was given no password argument" "! grep -q FAKEPGPW '$STUB_LOG/pg_dump.args'"
check "the live tasks database file and .env were not modified" "[ \"\$(cksum < '$T/database/database.sqlite')\" = '$TASKS_DB_SUM_BEFORE' ] && [ \"\$(cksum < '$T/.env')\" = '$ENV_SUM_BEFORE' ] && [ ! -e '$T/database/database.sqlite-wal' ]"
check "nothing was added to or removed from any app folder" "[ \"\$(find '$H'/*.$D -type f ! -path '*/press/*' | sort | cksum)\" = '$TREE_BEFORE' ]"

