#!/usr/bin/env bash
# Fake-host test of tools/backup-host.sh. No network, no real database, no real crontab: HOME is a temp dir,
# `mysqldump`, `pg_dump` and `crontab` are stubs (and `flock` a perl stand-in where the machine has none). Runs in CI
# (Linux, real flock) and locally. Every output of the tool is collected and scanned for the fake secrets at the end.
# shellcheck disable=SC2010
set -uo pipefail
ROOT_REPO="$(cd "$(dirname "$0")/.." && pwd)"
W="$(mktemp -d)"
BGPIDS=""
cleanup() { touch "$W/stop" 2>/dev/null; for p in $BGPIDS; do kill "$p" 2>/dev/null; done; rm -rf "$W"; }
trap cleanup EXIT
export HOME="$W/home"; SHIM="$W/shim"; STUB_LOG="$W/stublog"
mkdir -p "$HOME/bin" "$SHIM" "$STUB_LOG"
export PATH="$SHIM:$PATH" STUB_LOG CRONTAB_FILE="$W/crontab.txt"
unset DOT_BACKUP_PASSFILE DOT_BACKUP_KEEP DOT_BACKUP_PARALLEL DOT_BACKUP_TIMEOUT DOT_BACKUP_SQLITE_TOOL PHP_BIN BASE_DOMAIN
FAIL=0; ok() { echo "ok   - $1"; }; bad() { echo "FAIL - $1"; FAIL=1; }
check() { if eval "$2"; then ok "$1"; else bad "$1"; echo "$OUT" | head -n 12 | sed 's/^/       | /'; fi; }
sha() { if command -v sha256sum >/dev/null; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi; }
ALL="$W/all-output.txt"; : > "$ALL"
OUT=""; RC=0
runout() { OUT="$("$@" 2>&1)"; RC=$?; printf '%s\n' "$OUT" >> "$ALL"; }
bk() { bash "$HOME/bin/dot-backup" "$@"; }
BKR="$HOME/dot-backups"

# ---- stand-ins -------------------------------------------------------------------------------------------------
if ! command -v flock >/dev/null; then
  command -v perl >/dev/null || { echo "need flock or perl"; exit 1; }
  cat > "$SHIM/flock" <<'PL'
#!/usr/bin/perl
use Fcntl qw(:flock F_SETFD); my ($nb, $wait) = (0, undef);
while (@ARGV && $ARGV[0] =~ /^-/) { my $o = shift; if ($o eq '-n') { $nb = 1 } elsif ($o eq '-w') { $wait = shift } }
my $t = shift; my $fh;
if ($t =~ /^\d+$/) { open($fh, ">&=", $t) or exit 1 } else { open($fh, ">", $t) or exit 1; fcntl($fh, F_SETFD, 0) }
if ($nb) { flock($fh, LOCK_EX | LOCK_NB) or exit 1 }
elsif (defined $wait) { my $end = time + $wait; until (flock($fh, LOCK_EX | LOCK_NB)) { exit 1 if time >= $end; select(undef, undef, undef, 0.2) } }
else { flock($fh, LOCK_EX) or exit 1 }
exec @ARGV if @ARGV; exit 0;
PL
  chmod +x "$SHIM/flock"; echo "(no flock on this machine: perl stand-in used; CI runs the real one)"
fi
cat > "$SHIM/crontab" <<'SH'
#!/bin/sh
if [ "$1" = "-l" ]; then [ -f "$CRONTAB_FILE" ] && cat "$CRONTAB_FILE" || { echo "no crontab for user" >&2; exit 1; }; else { echo "# DO NOT EDIT THIS FILE - edit the master and reinstall."; cat "$1"; echo; } > "$CRONTAB_FILE"; fi
SH
cat > "$SHIM/mysqldump" <<'SH'
#!/bin/sh
case "$1" in --help) echo "  --no-tablespaces   Do not dump tablespaces"; exit 0;; esac
echo "$@" >> "$STUB_LOG/mysqldump.args"
cnf=""; for a in "$@"; do case "$a" in --defaults-extra-file=*) cnf="${a#*=}";; esac; done
[ -f "$cnf" ] || { echo "stub: no defaults file" >&2; exit 9; }
[ "$(ls -ld "$cnf" | cut -c1-10)" = "-rw-------" ] || { echo "stub: defaults file is not mode 600" >&2; exit 9; }
echo "$cnf" >> "$STUB_LOG/cnf.paths"; cp "$cnf" "$STUB_LOG/cnf.copy"
[ -n "${STUB_SLEEP:-}" ] && sleep "$STUB_SLEEP"
if [ -n "${STUB_DEPRECATED:-}" ]; then echo "mysqldump: Deprecated program name. It will be removed in a future release, use '/usr/bin/mariadb-dump' instead" >&2; fi
if [ -n "${STUB_FAIL:-}" ]; then echo "Access denied for user 'mines'@'localhost' (using password: YES) pw=$STUB_PW" >&2; exit 2; fi
echo "-- MySQL dump (stub)"; echo "CREATE TABLE t (id int);"; echo "INSERT INTO t VALUES (1),(2),(3);"; echo "-- Dump completed on 2026-10-22 02:40:00"
SH
cat > "$SHIM/pg_dump" <<'SH'
#!/bin/sh
echo "$@" >> "$STUB_LOG/pg_dump.args"
[ -f "$PGPASSFILE" ] || { echo "stub: no PGPASSFILE" >&2; exit 9; }
[ "$(ls -ld "$PGPASSFILE" | cut -c1-10)" = "-rw-------" ] || { echo "stub: pgpass is not mode 600" >&2; exit 9; }
echo "$PGPASSFILE" >> "$STUB_LOG/pgpass.paths"; cp "$PGPASSFILE" "$STUB_LOG/pgpass.copy"
echo "-- PostgreSQL database dump (stub)"; echo "CREATE TABLE t (id int);"; echo "-- PostgreSQL database dump complete"
SH
chmod +x "$SHIM/crontab" "$SHIM/mysqldump" "$SHIM/pg_dump"
cp "$ROOT_REPO/tools/backup-host.sh" "$HOME/bin/dot-backup"; chmod 755 "$HOME/bin/dot-backup"

HAVE_SQLITE=0; command -v sqlite3 >/dev/null && HAVE_SQLITE=1
HAVE_PHP=0; command -v php >/dev/null && php -r 'exit(class_exists("SQLite3")?0:1);' 2>/dev/null && HAVE_PHP=1
[ $HAVE_SQLITE = 1 ] || [ $HAVE_PHP = 1 ] || { echo "this test needs sqlite3 or php with the sqlite3 extension"; exit 1; }
sql() { # file statement...   (whichever tool exists)
  local f="$1"; shift
  if [ $HAVE_SQLITE = 1 ]; then sqlite3 "$f" "$@"; else DOT_F="$f" DOT_S="$*" php -r '$d=new SQLite3(getenv("DOT_F")); $d->exec(getenv("DOT_S"));'; fi
}
mk_sqlite() { # file rows [wal]
  rm -f "$1"
  sql "$1" "CREATE TABLE items(id INTEGER PRIMARY KEY, v TEXT); CREATE TABLE users(id INTEGER PRIMARY KEY, name TEXT); INSERT INTO users(name) VALUES ('a'),('b');"
  local i=1; local ins=""
  while [ $i -le "$2" ]; do ins="$ins INSERT INTO items(v) VALUES ('row$i');"; i=$((i + 1)); done
  sql "$1" "$ins"
  [ "${3:-}" = wal ] && sql "$1" "PRAGMA journal_mode=WAL;" > /dev/null
  return 0
}

# Names of secret-bearing .env variables are assembled here so this file holds no literal assignment of a secret.
KAPP="APP_""KEY"; KPW="DB_PASS""WORD"; KMAIL="MAIL_PASS""WORD"
ev() { printf '%s=%s\n' "$1" "$2"; }

