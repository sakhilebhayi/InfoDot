DP="$H/dopemine.$D/dopemine"; mkapp "$DP"; mkdir -p "$DP/storage/backups" "$H/dbs"; mk_sqlite "$H/dbs/dope.sqlite" 7
{ ev "$KAPP" "base64:FAKEKEY-DOPE="; echo 'DB_CONNECTION=sqlite'; echo "DB_DATABASE=$H/dbs/dope.sqlite"; } > "$DP/.env"; echo own > "$DP/storage/backups/dopemine-2026.sqlite"
