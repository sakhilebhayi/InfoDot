        <h1 class="ix-h1">Questions people ask</h1>

        <h2>What is InfoDot?</h2>
        <p>A place to ask business questions, learn from people who have faced the same problem, and follow solutions that have been checked. It is also the account that opens every platform in the Dot.Eco-system.</p>

        <h2>Who is it for?</h2>
        <p>People starting or running a business, and the people who work for them. You can arrive with an idea and no plan, or with an established problem.</p>

        <h2>Do I need an account?</h2>
        <p>You can search the public questions and solutions without one. To open a result in full, ask, answer, see your company's work or open other platforms, you need an account.</p>

        <h2>Who can see my question?</h2>
        <p>Your company, by default. It becomes public only if someone chooses to make it public. People in other companies cannot open it.</p>

        <h2>How do I know an answer is any good?</h2>
        <p>Each answer shows how it earned its place: accepted by the person who asked, or verified by a moderator who did not write it. Content a moderator has hidden is recorded with the reason.</p>

        <h2>Does AI write the answers?</h2>
        <p>No. Answers come from people. Where the Dot.Eco-system uses automation to suggest something, such as pointing a moderator to a good answer, a person decides and the record shows who.</p>

        <h2>Is this legal, tax or financial advice?</h2>
        <p>No. It is shared experience. Check anything that affects your legal, tax or financial position with a qualified professional before you rely on it.</p>

        <h2>Which platforms can I open?</h2>
        <p>Every live platform in the Dot.Eco-system, with the same account. After you sign in, the Platforms page lists them and opens each one signed in.</p>

        <h2>How is my personal information handled?</h2>
        <p>Read the <a href="{{ route('policy') }}">privacy policy</a> and the <a href="{{ route('cookies') }}">cookie policy</a>. For requests about your information, write to <a href="mailto:privacy@infodot.co.za">privacy@infodot.co.za</a>.</p>

        <h2>Something is wrong, or I need help.</h2>
        <p>Use the <a href="{{ route('contact') }}">contact form</a>. To report a question or answer, use the report link on it. To raise a complaint, see <a href="{{ route('complains') }}">how to complain</a>.</p>

