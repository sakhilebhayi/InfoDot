import fs from 'node:fs';
import path from 'node:path';
import { a11yDir, type Violation } from './a11y';
import { repoRoot } from './env';

type Recorded = { group: string; scheme: string; scanned: string[]; violations: Violation[] };

const reportFile = path.join(repoRoot, 'docs', 'programme', 'r49', 'ACCESSIBILITY_SCAN.md');
const order = ['critical', 'serious', 'moderate', 'minor', 'unknown'];
const groups = ['public', 'owner', 'moderator'];
const schemes = ['light', 'dark'];

/** What the first scan (2026-11-13) found and R-49 fixed, kept with the report so the history is not lost on a rewrite. */
const fixedDuringR49 = [
    '## Found by the first scan and fixed in R-49',
    '',
    '| Rule | Impact | Where | Elements | What was done |',
    '|---|---|---|---|---|',
    '| label | critical | `/business/{uuid}/edit`: the logo and cover file fields | 2 (4 over both schemes) | Each field has a name ("Logo picture", "Cover photograph"). |',
    '| aria-required-children | critical | The search suggestions on every signed-in page | 1 (2 over both schemes) | The five quick links inside the list box are options, like everything else in it. |',
    '| label-content-name-mismatch | serious | The company menu button on every signed-in page | 1 per page | The button is named by its own text, with "Company menu:" in front for a screen reader, instead of a label that left the company name out. |',
    '| label-content-name-mismatch | serious | The reply count beside each question on `/questions`, `/solution-results` and `/topics/{topic}` | 1 per question | The link is named by its own text ("3 replies"); the stencil numeral "03" is hidden from a screen reader. |',
    '',
    'The two name rows together were 84 elements over both colour schemes. A few of those were the show-password button, counted before its icon font had loaded; the scan now waits for fonts and it no longer appears.',
    'The first scan found no moderate or minor violations.',
    '',
    'The same pass fixed three keyboard problems the scan cannot see (`i-keyboard.spec.ts`): the account dialogs did not open at all, a dialog closed without giving focus back, and the top-bar menus closed on Escape leaving focus on a link that was no longer on screen.',
];

/**
 * Write docs/programme/r49/ACCESSIBILITY_SCAN.md from what the scan specs recorded. Only a complete scan (every
 * group in both colour schemes) replaces the file, so running one spec on its own never leaves half a report.
 */
export function writeAccessibilityReport(): void {
    if (!fs.existsSync(a11yDir)) {
        return;
    }
    const recorded: Recorded[] = fs.readdirSync(a11yDir).filter((f) => f.endsWith('.json')).sort()
        .map((f) => JSON.parse(fs.readFileSync(path.join(a11yDir, f), 'utf8')));
    if (!groups.every((g) => schemes.every((s) => recorded.some((r) => r.group === g && r.scheme === s)))) {
        return;
    }

    const all = recorded.flatMap((r) => r.violations);
    const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\s+/g, ' ');
    const lines: string[] = [];

    lines.push('# R-49 accessibility scan');
    lines.push('');
    lines.push('Written by the browser tests (`tests/Browser/specs/h-accessibility.spec.ts`, axe-core through Playwright, desktop Chromium at 1440 x 900).');
    lines.push('Rules: WCAG 2.0, 2.1 and 2.2, levels A and AA. Every page is scanned in the light and in the dark colour scheme.');
    lines.push('The spec fails on any serious or critical violation; moderate and minor ones are listed here and do not fail it.');
    lines.push('An automated scan finds only part of what WCAG asks for: keyboard use is tested separately (`i-keyboard.spec.ts`), and screen-reader use is not tested.');
    lines.push('');
    lines.push('Do not edit this file by hand: `npm run test:browser` rewrites it when the whole scan has run.');
    lines.push('');
    lines.push('## Totals');
    lines.push('');
    lines.push('| Impact | Rules broken (page and scheme counted separately) | Elements |');
    lines.push('|---|---|---|');
    for (const impact of order) {
        const of = all.filter((v) => v.impact === impact);
        if (of.length > 0 || impact === 'critical' || impact === 'serious') {
            lines.push(`| ${impact} | ${of.length} | ${of.reduce((sum, v) => sum + v.count, 0)} |`);
        }
    }
    lines.push('');
    lines.push('## Pages scanned');
    lines.push('');
    for (const group of groups) {
        const light = recorded.find((r) => r.group === group && r.scheme === 'light');
        lines.push(`- **${group}** (${light?.scanned.length ?? 0} pages, each in light and dark): ${(light?.scanned ?? []).map((p) => `\`${p}\``).join(', ')}`);
    }
    lines.push('');
    lines.push('## By rule');
    lines.push('');
    if (all.length === 0) {
        lines.push('No violations.');
    } else {
        lines.push('| Rule | Impact | What it means | Pages | Elements |');
        lines.push('|---|---|---|---|---|');
        const rules = Array.from(new Set(all.map((v) => v.rule)));
        rules.sort((a, b) => order.indexOf(all.find((v) => v.rule === a)!.impact) - order.indexOf(all.find((v) => v.rule === b)!.impact) || a.localeCompare(b));
        for (const rule of rules) {
            const of = all.filter((v) => v.rule === rule);
            lines.push(`| ${rule} | ${of[0].impact} | ${cell(of[0].help)} | ${new Set(of.map((v) => v.path)).size} | ${of.reduce((sum, v) => sum + v.count, 0)} |`);
        }
        lines.push('');
        lines.push('## Every violation');
        lines.push('');
        lines.push('| Rule | Impact | Page | Scheme | Count | First selectors |');
        lines.push('|---|---|---|---|---|---|');
        const sorted = [...all].sort((a, b) => order.indexOf(a.impact) - order.indexOf(b.impact) || a.rule.localeCompare(b.rule) || a.path.localeCompare(b.path) || a.page.localeCompare(b.page) || a.scheme.localeCompare(b.scheme));
        for (const v of sorted) {
            lines.push(`| ${v.rule} | ${v.impact} | \`${v.path}\` (${v.page}) | ${v.scheme} | ${v.count} | ${v.selectors.slice(0, 3).map((s) => `\`${cell(s)}\``).join('<br>')} |`);
        }
    }
    lines.push('');
    lines.push(...fixedDuringR49);
    lines.push('');

    fs.mkdirSync(path.dirname(reportFile), { recursive: true });
    fs.writeFileSync(reportFile, lines.join('\n'));
}
